import importlib.util
import json
import os
from pathlib import Path
import shutil
import stat
import subprocess
import sys
import tempfile
import unittest
from unittest.mock import patch


SCRIPT = Path(__file__).resolve().parents[1] / "skills/rpgmaker-plugins/scripts/plugins_js.py"
spec = importlib.util.spec_from_file_location("plugins_js", SCRIPT)
editor = importlib.util.module_from_spec(spec)
spec.loader.exec_module(editor)


def plugin(name, **extra):
    return {"name": name, "status": True, "description": "中文", "parameters": {"Count": "3"}, **extra}


def source(plugins):
    return ("// Generated by RPG Maker.\nvar $plugins =\n" + json.dumps(plugins, ensure_ascii=False) + ";\n").encode()


def plan(*ops):
    return {"version": 1, "operations": list(ops)}


class EditorTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.path = self.root / "plugins.js"
        self.original = source([plugin("Base"), plugin("Example", custom={"x": 1})])
        self.path.write_bytes(self.original)
        self.planpath = self.root / "plan.json"

    def cli(self, *args, ok=True):
        run = subprocess.run([sys.executable, str(SCRIPT), "--file", str(self.path), *args],
                             capture_output=True, text=True)
        self.assertEqual(run.returncode, 0 if ok else 1, run.stderr)
        return json.loads(run.stdout if ok else run.stderr)

    def save_plan(self, value):
        self.planpath.write_text(json.dumps(value), encoding="utf-8")

    def test_inspect_validate(self):
        self.assertEqual(self.cli("inspect")["plugins"][1]["custom"], {"x": 1})
        self.assertEqual(self.cli("validate")["count"], 2)

    def test_summary_and_subfolder_selector(self):
        self.path.write_bytes(source([plugin("grace/Example")]))
        result = self.cli("inspect", "--summary", "--name", "grace/Example")
        self.assertEqual(result["plugins"], [{"name": "grace/Example", "status": True, "parameter_count": 1}])
        self.cli("inspect", "--name", "Example", ok=False)

    def test_preview_write_and_restore_exact_bytes(self):
        self.path.chmod(0o640)
        self.save_plan(plan({"op": "update", "name": "Example", "status": False,
                             "parameters": {"Text": '中文\\n"quoted"', "Nested": '["{\\"n\\":\\"1\\"}"]'}}))
        preview = self.cli("apply", "--plan", str(self.planpath))
        self.assertTrue(preview["changed"])
        self.assertFalse(preview["written"])
        self.assertEqual(self.path.read_bytes(), self.original)
        self.assertEqual({p.name for p in self.root.iterdir()}, {"plugins.js", "plan.json"})
        written = self.cli("apply", "--plan", str(self.planpath), "--write", "--expect-sha256", preview["sha256"])
        self.assertTrue(written["written"])
        self.assertEqual(Path(written["backup"]).read_bytes(), self.original)
        self.assertEqual(stat.S_IMODE(self.path.stat().st_mode), 0o640)
        item = self.cli("inspect")["plugins"][1]
        self.assertFalse(item["status"])
        self.assertEqual(item["parameters"]["Count"], "3")
        self.assertEqual(item["custom"], {"x": 1})
        restored = self.cli("restore", "--backup", written["backup"], "--write",
                            "--expect-sha256", written["after_sha256"])
        self.assertTrue(restored["written"])
        self.assertEqual(self.path.read_bytes(), self.original)

    def test_add_move_remove_unset(self):
        result = editor.transform([plugin("A"), plugin("B")], plan(
            {"op": "add", "plugin": plugin("C"), "before": "B"},
            {"op": "move", "name": "A", "after": "B"},
            {"op": "update", "name": "C", "unset_parameters": ["Count"]},
            {"op": "remove", "name": "B"}))
        self.assertEqual([p["name"] for p in result], ["C", "A"])
        self.assertEqual(result[0]["parameters"], {})

    def test_noop_does_not_reformat_or_backup(self):
        self.save_plan(plan({"op": "update", "name": "Example", "status": True}))
        result = self.cli("apply", "--plan", str(self.planpath), "--write",
                          "--expect-sha256", editor.digest(self.original))
        self.assertFalse(result["changed"])
        self.assertFalse(result["written"])
        self.assertEqual(self.path.read_bytes(), self.original)
        self.assertFalse((self.root / ".plugins-js-backups").exists())

    def test_invalid_later_operation_leaves_file_unchanged(self):
        self.save_plan(plan({"op": "remove", "name": "Base"}, {"op": "remove", "name": "Missing"}))
        self.cli("apply", "--plan", str(self.planpath), "--write",
                 "--expect-sha256", editor.digest(self.original), ok=False)
        self.assertEqual(self.path.read_bytes(), self.original)
        self.assertFalse((self.root / ".plugins-js-backups").exists())

    def test_write_requires_current_fingerprint(self):
        self.save_plan(plan({"op": "remove", "name": "Base"}))
        self.cli("apply", "--plan", str(self.planpath), "--write", ok=False)
        self.cli("apply", "--plan", str(self.planpath), "--write", "--expect-sha256", "stale", ok=False)
        self.assertEqual(self.path.read_bytes(), self.original)

    def test_bom_crlf_and_comments_preserved(self):
        raw = b'\xef\xbb\xbf/* header */\r\nvar $plugins =\r\n' + json.dumps([plugin("A")]).encode() + b'; // tail\r\n'
        parsed = editor.parse(raw)
        output = editor.render(parsed, editor.transform(parsed[3], plan({"op": "update", "name": "A", "status": False})))
        self.assertTrue(output.startswith(b'\xef\xbb\xbf/* header */\r\nvar $plugins =\r\n'))
        self.assertTrue(output.endswith(b'; // tail\r\n'))
        self.assertNotIn(b'\n', output.replace(b'\r\n', b''))
        self.assertFalse(editor.parse(output)[3][0]["status"])

    def test_rejects_executable_and_non_json_input(self):
        samples = [b'var $plugins = []; alert(1);', b'var $plugins = (() => [])();',
                   b'var $plugins = [/*comment*/];', b'var $plugins = [1,];',
                   b'var $plugins = []; var $plugins = [];', b'var $plugins = NaN;',
                   b'var $plugins = [{"name":"A","name":"B"}];']
        for raw in samples:
            with self.subTest(raw=raw), self.assertRaises(ValueError):
                editor.parse(raw)

    def test_string_parameters_only(self):
        for bad in [True, 1, None, [], {}]:
            with self.subTest(bad=bad), self.assertRaises(editor.Invalid):
                editor.transform([plugin("A")], plan({"op": "update", "name": "A", "parameters": {"x": bad}}))

    def test_rejects_typos_ambiguous_names_and_invalid_positions(self):
        bad_ops = [{"op": "update", "name": "A", "enabled": False},
                   {"op": "move", "name": "A"}, {"op": "move", "name": "A", "before": "A"},
                   {"op": "move", "name": "A", "before": "B", "after": "B"},
                   {"op": "update", "name": "A", "status": "false"},
                   {"op": "add", "plugin": plugin("a")},
                   {"op": "update", "name": "A", "unset_parameters": ["missing"]},
                   {"op": "update", "name": "A", "parameters": {"Count": "4"}, "unset_parameters": ["Count"]}]
        for op in bad_ops:
            with self.subTest(op=op), self.assertRaises(editor.Invalid):
                editor.transform([plugin("A"), plugin("B")], plan(op))
        with self.assertRaises(editor.Invalid):
            editor.transform([plugin("A"), plugin("A")], plan({"op": "remove", "name": "A"}))

    def test_lock_blocks_write(self):
        lock = self.path.with_name("plugins.js.rpgmaker.lock")
        lock.touch()
        with self.assertRaises(FileExistsError):
            editor.commit(self.path, self.original, source([]))
        self.assertTrue(lock.exists())
        self.assertEqual(self.path.read_bytes(), self.original)

    def test_changed_source_and_backup_failure_do_not_replace(self):
        with self.assertRaises(editor.Invalid):
            editor.commit(self.path, b"stale", source([]))
        (self.root / ".plugins-js-backups").write_text("not a directory")
        with self.assertRaises(OSError):
            editor.commit(self.path, self.original, source([]))
        self.assertEqual(self.path.read_bytes(), self.original)
        self.assertFalse(self.path.with_name("plugins.js.rpgmaker.lock").exists())

    def test_replace_failure_keeps_original_and_removes_temp(self):
        with patch.object(editor.os, "replace", side_effect=OSError("simulated")):
            with self.assertRaises(OSError):
                editor.commit(self.path, self.original, source([]))
        self.assertEqual(self.path.read_bytes(), self.original)
        self.assertEqual(list(self.root.glob(".plugins-*")), [self.root / ".plugins-js-backups"])

    def test_restore_damaged_target(self):
        backup = self.root / "backup.js"
        backup.write_bytes(self.original)
        self.path.write_bytes(b"broken\xff")
        preview = self.cli("restore", "--backup", str(backup))
        self.cli("restore", "--backup", str(backup), "--write", "--expect-sha256", preview["sha256"])
        self.assertEqual(self.path.read_bytes(), self.original)

    def test_symlink_rejected(self):
        self.path.unlink()
        actual = self.root / "actual.js"
        actual.write_bytes(self.original)
        self.path.symlink_to(actual)
        self.cli("inspect", ok=False)
        self.assertEqual(actual.read_bytes(), self.original)

    def test_unknown_fields_and_empty_placeholders_survive(self):
        items = [plugin(""), plugin("A", extra=[1, "text"]), plugin("")]
        changed = editor.transform(items, plan({"op": "update", "name": "A", "status": False}))
        self.assertEqual(changed[0], items[0])
        self.assertEqual(changed[2], items[2])
        self.assertEqual(changed[1]["extra"], [1, "text"])

    @unittest.skipUnless(os.environ.get("RPGMAKER_TEST_PROJECT"), "Set RPGMAKER_TEST_PROJECT for read-only project integration")
    def test_real_project_copy_roundtrip(self):
        project_file = Path(os.environ["RPGMAKER_TEST_PROJECT"]) / "js/plugins.js"
        raw = project_file.read_bytes()
        before = editor.parse(raw)[3]
        self.assertTrue(before)
        self.path.write_bytes(raw)
        selected = next(p for p in before if p["name"] and p["parameters"])
        parameter = next(iter(selected["parameters"]))
        changed_value = selected["parameters"][parameter] + '\n测试"\\'
        self.save_plan(plan({"op": "update", "name": selected["name"],
                             "status": not selected["status"], "parameters": {parameter: changed_value}}))
        preview = self.cli("apply", "--plan", str(self.planpath))
        written = self.cli("apply", "--plan", str(self.planpath), "--write", "--expect-sha256", preview["sha256"])
        after = self.cli("inspect")["plugins"]
        for original, modified in zip(before, after):
            if original["name"] == selected["name"]:
                expected = editor.copy.deepcopy(original)
                expected["status"] = not original["status"]
                expected["parameters"][parameter] = changed_value
                self.assertEqual(modified, expected)
            else:
                self.assertEqual(modified, original)
        if shutil.which("node"):
            checked = subprocess.run(["node", "--check", str(self.path)], capture_output=True, text=True)
            self.assertEqual(checked.returncode, 0, checked.stderr)
        self.cli("restore", "--backup", written["backup"], "--write", "--expect-sha256", written["after_sha256"])
        self.assertEqual(self.path.read_bytes(), raw)
        self.assertEqual(project_file.read_bytes(), raw, "Real project must remain unchanged")


if __name__ == "__main__":
    unittest.main()
